import { NextRequest, NextResponse } from 'next/server';
import { db } from '@/lib/db';

export async function POST(request: NextRequest) {
  try {
    const body = await request.json();
    const { 
      full_name, 
      email, 
      role, 
      institution, 
      photo_url, 
      theme = 'sbg', 
      access_level = 'Full Conference & Workshops',
      donation_amount,
      donation_utr 
    } = body;

    if (!full_name || !email) {
      return NextResponse.json({ error: 'Full name and email are required' }, { status: 400 });
    }

    const cleanEmail = email.trim().toLowerCase();

    // 1. Check if candidate is registered for an event
    const registration = db.getRegistrationByEmail(cleanEmail);
    const isRegistered = Boolean(registration);

    // Check if candidate already has an active verified badge with an issued pass code
    const existing = db.getBadgeByEmail(cleanEmail);
    if (existing && existing.status === 'verified' && existing.code) {
      return NextResponse.json({
        success: true,
        isFree: existing.source === 'event_registration',
        status: existing.status,
        badge: existing,
        message: 'Your official pass code has already been issued! (Limit: 1 official badge per registered participant).',
      });
    }

    if (isRegistered && registration) {
      const event = db.getEventById(registration.event_id, true);
      const roleMap: Record<string, string> = {
        attendee: 'Official Attendee',
        speaker: 'Featured Speaker',
        sponsor: 'Official Sponsor',
        volunteer: 'Community Volunteer',
      };

      const finalRole = roleMap[registration.role] || 'Official Attendee';

      const badge = db.createBadgeApplication({
        code: null, // Pass code will be generated by Admin in the Admin Panel
        full_name: registration.full_name, // Strictly locked to registration full name
        email: cleanEmail,
        role: finalRole,
        institution: registration.college || 'Noida International University',
        photo_url: photo_url || null,
        source: 'event_registration',
        event_id: registration.event_id,
        event_title: event?.title || 'AWS SBG Official Event',
        registration_code: registration.registration_code,
        donation_amount: 0,
        status: 'pending', // Pending Admin approval & pass code issuance
        qr_payload: null,
        access_level,
        theme,
        verified_by: null,
        verified_at: null,
      });

      return NextResponse.json({
        success: true,
        isFree: true,
        status: 'pending',
        badge,
        message: 'Application submitted! Matched registered event participant (Free ₹0.00). Admin will verify and generate your official pass code.',
      });
    } else {
      // Not registered -> requires donation
      const amount = Number(donation_amount);
      if (isNaN(amount) || amount < 10) {
        return NextResponse.json({
          error: 'Event registration not found. Please provide a community support donation of at least ₹49 to claim this official badge.',
          donationRequired: true,
        }, { status: 400 });
      }

      const utr = donation_utr?.trim() || `UPI/DON-${Date.now().toString().slice(-6)}`;

      const badge = db.createBadgeApplication({
        code: null, // Pass code will be generated by Admin in the Admin Panel
        full_name: full_name.trim(),
        email: cleanEmail,
        role: role || 'Community Builder',
        institution: institution || 'Noida International University',
        photo_url: photo_url || null,
        source: 'community_donation',
        donation_amount: amount,
        donation_utr: utr,
        status: 'pending', // Pending Admin verification of UTR & pass code issuance
        qr_payload: null,
        access_level,
        theme,
        verified_by: null,
        verified_at: null,
      });

      return NextResponse.json({
        success: true,
        isFree: false,
        status: 'pending',
        badge,
        message: `Thank you for your ₹${amount} contribution (UTR: ${utr})! Your application is pending Admin verification and pass code generation.`,
      });
    }
  } catch (error) {
    console.error('Error applying for badge:', error);
    return NextResponse.json({ error: 'Failed to process badge application' }, { status: 500 });
  }
}
